/**
 * AI 에 보내기 전 개인정보 마스킹.
 * 전화번호·차량번호는 정규식으로, 사람 이름은 프로토타입에서는 "○○○ 학부모" 같은
 * 흔한 패턴만 처리한다. (정밀한 이름 탐지는 추후 별도 모델 호출로 대체)
 */
export function maskText(text: string): string {
  let t = text;
  // 휴대폰·일반 전화
  t = t.replace(/(\+82[- ]?)?0\d{1,2}[- .]?\d{3,4}[- .]?\d{4}/g, "[전화번호]");
  // 차량번호: 12가3456, 123가4567, 서울12가3456
  t = t.replace(/([가-힣]{2})?\s?\d{2,3}\s?[가-힣]\s?\d{4}/g, "[차량번호]");
  // "홍길동 학부모", "김OO 엄마" 류
  t = t.replace(/[가-힣]{2,4}\s?(학부모|엄마|아빠|어머니|아버지|선생님)/g, "[이름] $1");
  return t;
}
